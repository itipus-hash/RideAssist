    /** 官方 `calcCrc16(data, offset, len)`，初值 0xFFFF */
    fun crc16(data: ByteArray, offset: Int, len: Int): Int {
        var i = (0xFFFF shr 8) and 0xFF
        var i2 = 0xFFFF and 0xFF
        for (k in 0 until len) {
            val idx = (i2 xor (data[offset + k].toInt() and 0xFF)) and 0xFF
            val i5 = i xor CRC_TAB_H[idx]
            i = CRC_TAB_L[idx]
            i2 = i5
        }
        return ((i and 0xFF) shl 8) or (i2 and 0xFF)
    }

    /**
     * 构造读请求（官方 `CodingGetDataMsg`）。
     *
     * @param addr 寄存器地址（2 字节大端）
     * @param dataLen 期望回包数据长度（决定回包总长 = dataLen*2+5）
     * @param saAdd 首字节，官方读 0x0000 时传 0，其余传 1
     */
    fun buildReadFrame(addr: Int, dataLen: Int, saAdd: Int = 1): ByteArray {
        val b = ByteArray(REQUEST_SIZE)
        b[0] = saAdd.toByte()
        b[1] = 0x03
        b[2] = ((addr shr 8) and 0xFF).toByte()      // Addr 高字节（大端）
        b[3] = (addr and 0xFF).toByte()// Addr 低字节
        b[4] = ((dataLen shr 8) and 0xFF).toByte()    // data_len 高字节
        b[5] = (dataLen and 0xFF).toByte()
        val crc = crc16(b, 0, 6)
        b[6] = (crc and 0xFF).toByte()                // CRC 低字节
        b[7] = ((crc shr 8) and 0xFF).toByte()        // CRC 高字节
        return b
    }

    /** 帧结构校验（不含 CRC 验证，官方也不验回包 CRC） */
    fun checkFrame(frame: ByteArray): Boolean {
        if (frame.size < MIN_FRAME_SIZE) return false
        if (frame[1].toInt() and 0xFF != 0x03) return false
        return true
    }

    /** 提取数据区：跳过 3 字节头 + 2 字节 CRC */
    fun payloadOf(frame: ByteArray): ByteArray {
        if (frame.size < 5) return ByteArray(0)
        val start = 3
        val end = frame.size - 2
        if (end <= start) return ByteArray(0)
        return frame.copyOfRange(start, end)
    }

    fun toHex(bytes: ByteArray): String =
        bytes.joinToString("") { "%02X".format(it) }
