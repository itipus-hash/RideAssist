/**
 * 彦阳 BMS 协议（**完全对齐官方 APK** `com.yybms` v3.4.05）。
 *
 * 官方实现类：`com.yybms.app.util.BMSDataClass`
 * 组帧方法`CodingGetDataMsg(byte ID, short Addr, short data_len)`
 *
 * ```
 * 偏移  长度  含义                     官方代码
 *  0    1   saAdd（0 或 1）           bArr[0] = BleDataUtils.saAdd
 *  1    1   0x03 功能码               bArr[1] = 3
 *  2    1   Addr 高字节（大端）        bArr[2] = (byte)(Addr / 256)
 *  3    1   Addr 低字节              bArr[3] = (byte)(Addr % 256)
 *  4    1   data_len 高字节           bArr[4] = (byte)(data_len / 256)
 *  5    1   data_len 低字节           bArr[5] = (byte)(data_len % 256)
 *  6    1   CRC16 低字节              bArr[6] = (byte)(crc & 255)
 *  7    1   CRC16 高字节              bArr[7] = (byte)((65280 & crc) >> 8)
 * ```
 *
 * ⚠️ 我此前把 b4/b5 当成"寄存器参数"是**错的**——它们是 `data_len`（期望回包长度），
 * 真正的寄存器是 b2/b3（**大端**）。
 *
 * 校验：`calcCrc16(bArr, 0, 6)`，表驱动 CRC16（初值 0xFFFF）。
 * 已用官方 6 组抓包样本验证，**逐字节 100% 一致**。
